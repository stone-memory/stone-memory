const slugify = (value: string) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
const make = (
  slug: string,
  name: string,
  family: string,
  origin: string,
  tone: string,
  applications: string[],
  extra: Partial<Collection> = {}
): Collection => {
  const description =
    descriptions[slug] ??
    `${name}: ${tone} тон, походження — ${origin}. Застосування: ${applications.slice(0, 2).join(', ')}.`
  return {
    slug,
    name,
    material:
      family === 'Граніт' || family === 'Лабрадорит'
        ? 'granit'
        : family === 'Мармур'
          ? 'marmur'
          : family === 'Кварцит'
            ? 'kvarcyt'
            : family === 'Кварц'
              ? 'kvarc'
              : ['Онікс', 'Травертин', 'Вапняк'].includes(family)
                ? 'marmur' // вапнякові породи: той самий догляд і калькулятор, що в мармуру
                : 'keramohranit',
    family,
    origin,
    tone,
    finishes:
      family === 'Кварц'
        ? ['полірований', 'матовий']
        : family === 'Керамограніт'
          ? ['матовий', 'полірований']
          : ['полірований', 'шліфований'],
    thicknesses: family === 'Керамограніт' ? [6, 12] : [20, 30],
    applications,
    description,
    image: `/materials/${slug}.webp`,
    cardImage: `/materials/${slug}.webp`,
    care:
      ['Мармур', 'Онікс', 'Травертин', 'Вапняк'].includes(family)
        ? 'Нейтральний pH, просочення та негайне видалення кислот.'
        : 'Нейтральний засіб; для природного каменю перевіряти просочення.',
    relatedArticles: ['yak-vybraty-kamin-dlya-kukhni', 'yak-doglyadaty-za-granitnoyu-stilnytseyu'],
    relatedCategories: ['stilnytsi', 'fasady'],
    price: knownPrices[slug] ?? { value: 0, unit: 'м²', currency: 'грн' },
    ...extra,
  }
}
