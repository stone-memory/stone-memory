export function productType(stone: StoneItem): ProductType {
  const s = `${stone.shape ?? ""} ${stone.name ?? ""}`.toLowerCase()
  // Скульптури, плити, обеліски, урни, валуни — не стела на тумбі, тому
  // текст про «стелу з квітником» їм не пасує.
  if (/скульптур|надгробна плита|обеліск|колумбар|урна|валун|барельєф/.test(s)) return "special"
  if (s.includes("військов")) return "military"
  if (s.includes("дитяч")) return "child"
  if (s.includes("хрест")) return "cross"
  if (s.includes("європ")) return "european"
  if (s.includes("подвій") || s.includes("спарен")) return "double"
  if (s.includes("комплекс")) return "complex"
  return "single"
}

export function productComplexity(stone: StoneItem): Complexity | null {
  const src = `${stone.slug ?? ""} ${stone.name ?? ""}`.toLowerCase()
  if (/elitna|елітн/.test(src)) return "elitna"
  if (/skladna|складн/.test(src)) return "skladna"
  if (/standartna|стандартн/.test(src)) return "standartna"
  if (/bazova|базов/.test(src)) return "bazova"
  if (/prosta|прост/.test(src)) return "prosta"
  return null
}

