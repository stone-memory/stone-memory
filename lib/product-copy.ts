export function productStory(stone: StoneItem): ProductStory {
  const type = productType(stone)
  const complexity = productComplexity(stone)
  const base = TYPE_STORY[type]
  const entry = defaultStone(stone)

  const stoneSentence = `Основний камінь на фото — ${entry.name.toLowerCase()}: ${entry.look.replace(/\.$/, "").toLowerCase()}. ${entry.why}`
  const complexitySentence = complexity ? COMPLEXITY_TEXT[complexity] : ""

  return {
    type,
    typeLabel: TYPE_LABEL[type],
    complexity,
    intro: [base.intro, stoneSentence, complexitySentence].filter(Boolean).join("\n\n"),
    included: base.included,
    sizes: stone.sizeCm ? withRealSize(base.sizes, stone.sizeCm) : base.sizes,
    priceFactors: base.priceFactors,
    extras: base.extras,
    leadTime: base.leadTime,
    stone: entry,
  }
}

/**
 * Реальний розмір із картки має пріоритет над типовим: «стела 80×45×8, ділянка
 * 200×100 см» розбирається на частини й підміняє відповідні рядки.
 */
function withRealSize(defaults: { part: string; size: string }[], sizeCm: string) {
  const parsed = sizeCm
    .split(/[,;]/)
    .map((chunk) => chunk.trim())
    .map((chunk) => {
      const m = chunk.match(/^([а-яіїєґ'’]+)\s+(.+)$/i)
      return m ? { part: capitalize(m[1]), size: m[2].replace(/\s*см$/i, "") + " см" } : null
    })
    .filter((x): x is { part: string; size: string } => Boolean(x))
  if (parsed.length === 0) return defaults
  const parts = new Set(parsed.map((p) => p.part.toLowerCase()))
  return [...parsed, ...defaults.filter((d) => !parts.has(d.part.toLowerCase()))]
}

const capitalize = (s: string) => s.charAt(0).toUpperCase() + s.slice(1)

/** Коротка версія для meta description і карток списку. */
export function productSummary(stone: StoneItem): string {
  const story = productStory(stone)
  const price = stone.priceFrom ? ` Від ${stone.priceFrom.toLocaleString("uk-UA")} ₴ — у ціні ${story.included.slice(0, 3).join(", ")}.` : ""
  return `${story.typeLabel} з каменю ${story.stone.name.toLowerCase()}.${price} Виготовлення ${story.leadTime}, монтаж по Україні, гарантія 5 років.`
}
